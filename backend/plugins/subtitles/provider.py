from abc import ABC, abstractmethod
import os
import asyncio
from pydantic import BaseModel
from typing import Optional

class SubtitleResult(BaseModel):
    language: str
    duration: float
    segments: int
    word_count: int
    source: str
    srt_path: str

class TranscriptionProvider(ABC):
    """
    Interface for subtitle transcription providers.
    """
    @abstractmethod
    async def transcribe(self, video_path: str, output_path: str, language: str = "auto") -> SubtitleResult:
        """
        Transcribes a video and saves the output to a file (e.g. .srt).
        
        Args:
            video_path: The path to the input video file.
            output_path: The path where the subtitle file should be saved.
            language: The language of the audio (or 'auto' for detection).
            
        Returns:
            A SubtitleResult object with metadata and the path to the generated subtitle.
        """
        pass

class DummyProvider(TranscriptionProvider):
    """
    Dummy provider that creates a fake .srt file for testing.
    """
    async def transcribe(self, video_path: str, output_path: str, language: str = "auto") -> SubtitleResult:
        # Simulate transcription delay
        await asyncio.sleep(1)
        
        # Ensure directory exists
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        
        fake_srt = """1
00:00:01,000 --> 00:00:04,000
This is a fake subtitle generated by DummyProvider.

2
00:00:05,000 --> 00:00:08,000
It serves as a placeholder for testing purposes.
"""
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(fake_srt)
            
        return SubtitleResult(
            language="en" if language == "auto" else language,
            duration=8.0,
            segments=2,
            word_count=16,
            source="dummy",
            srt_path=output_path
        )
